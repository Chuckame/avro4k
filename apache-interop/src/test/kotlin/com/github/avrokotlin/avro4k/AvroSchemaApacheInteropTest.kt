/**
 * Guards the conversions between [AvroSchema] and Apache's [Schema] over every schema of the other modules' test suites,
 * plus the schemas avro4k generates for a representative set of classes.
 *
 * The fidelity checks go through the uncached conversions ([convertUncached]): the cached ones pair each node with its
 * source, so a cached round trip returns the very same instance and would compare nothing. The pairing itself is covered
 * by [AvroSchemaApacheIdentityTest].
 */
class AvroSchemaApacheInteropTest : FunSpec({
    val rootDir = File(System.getProperty("avro4k.rootDir") ?: error("Missing avro4k.rootDir system property"))

    val schemaFiles = schemaFiles(rootDir)

    test("finds the test suites' schema files") {
        // guards against a moved resources directory silently emptying the round-trip coverage
        (schemaFiles.size > 90) shouldBe true
    }

    val schemasFromFiles: List<Pair<String, Pair<Schema, AvroSchema>>> = parseSchemaFiles(rootDir)

    test("parses every schema file") {
        schemasFromFiles.size shouldBe schemaFiles.size - UNPARSEABLE_FILES.size
    }

    schemasFromFiles.forEach { (name, schemas) ->
        val (apacheSchema, parsedAvro4kSchema) = schemas
        context(name) {
            test("apache -> avro4k -> apache") {
                val roundTripped = apacheSchema.convertUncached().convertUncached()
                if (name in DEFAULTS_COERCED_BY_APACHE) {
                    roundTripped shouldBe apacheSchema.withNormalizedDefaults()
                } else {
                    roundTripped shouldBe apacheSchema
                }
            }
            test("apache -> avro4k -> apache -> avro4k is stable") {
                val avro4k = apacheSchema.convertUncached()
                avro4k.convertUncached().convertUncached() shouldBe avro4k
            }
            test("avro4k parsed from json -> apache -> avro4k") {
                if (name in DEFAULTS_COERCED_BY_APACHE) {
                    parsedAvro4kSchema.convertUncached().convertUncached() shouldBe apacheSchema.convertUncached()
                } else {
                    parsedAvro4kSchema.convertUncached().convertUncached() shouldBe parsedAvro4kSchema
                }
            }
            test("avro4k's json parser and the apache conversion agree") {
                if (name !in DEFAULTS_COERCED_BY_APACHE) {
                    apacheSchema.toAvro4k() shouldBe parsedAvro4kSchema
                }
            }
        }
    }

    context("schemas generated by avro4k") {
        GENERATED_SCHEMAS.forEach { serializer ->
            test(serializer.descriptor.serialName) {
                val apacheSchema = Avro.schema(serializer)
                val avro4k = apacheSchema.convertUncached()
                // Same json, but compared with a parsed schema: Apache compares defaults by json node type, and core builds some
                // defaults with a different node type than the parser (see "core's int defaults are big integer json nodes")
                avro4k.convertUncached().toString() shouldBe apacheSchema.toString()
                avro4k.convertUncached() shouldBe Schema.Parser().parse(apacheSchema.toString())
                avro4k.convertUncached().convertUncached() shouldBe avro4k
                AvroSchema.fromJsonString(apacheSchema.toString()) shouldBe avro4k
            }
        }
    }

    test("core's int defaults are big integer json nodes") {
        // Why the generated schemas are compared to their parsed json: Apache's field equality compares the default json nodes, including their type
        val field = Avro.schema(Everything.serializer()).getField("withDefault")
        Accessor.defaultValue(field).isBigInteger shouldBe true
        field.defaultVal() shouldBe null
        (Avro.schema(Everything.serializer()).toAvro4k() as AvroSchema.RecordSchema).getFieldByName("withDefault").defaultValue shouldBe JsonPrimitive(42)
    }

    test("a union default matching a later branch converts, as Apache Java accepts it") {
        val apache = Schema.Parser().parse("""{"type":"record","name":"R","fields":[{"name":"f","type":["null","string"],"default":"foo"}]}""")
        val avro4k = apache.toAvro4k() as AvroSchema.RecordSchema

        avro4k.fields.single().defaultValue shouldBe JsonPrimitive("foo")
        avro4k.toApacheSchema() shouldBe apache
    }

    test("recursive records keep their identity") {
        val schema = Avro.schema(Node.serializer()).toAvro4k() as AvroSchema.RecordSchema
        val next = schema.getFieldByName("next").schema as AvroSchema.UnionSchema
        next.types[1] shouldBeSameInstanceAs schema
        schema.convertUncached().convertUncached() shouldBe schema
    }

    test("field order is kept as a field prop") {
        val json = """{"type":"record","name":"R","fields":[{"name":"a","type":"int","order":"descending"},{"name":"b","type":"int","order":"ignore"}]}"""
        val apacheSchema = Schema.Parser().parse(json)
        val avro4k = apacheSchema.toAvro4k() as AvroSchema.RecordSchema
        avro4k.fields.map { it.props["order"]?.toString() } shouldBe listOf("\"descending\"", "\"ignore\"")
        avro4k shouldBe AvroSchema.fromJsonString(json)
        avro4k.convertUncached() shouldBe apacheSchema
    }

    test("the known exceptions are still exceptions") {
        // if one of those starts to round-trip, remove it from the list
        schemasFromFiles.filter { (name, schemas) -> name in DEFAULTS_COERCED_BY_APACHE && schemas.first.convertUncached().convertUncached() == schemas.first }
            .map { it.first }
            .shouldBeEmpty()
    }
}) {
    internal companion object {
        /**
         * Schemas whose field defaults Apache Avro coerces to the field's type ([Schema.Field.defaultVal]), which [toAvro4k] relies on,
         * so the textual default changes (e.g. `36` becomes `36.0` for a float field), and Apache's json node equality is textual.
         */
        val DEFAULTS_COERCED_BY_APACHE =
            setOf(
                "kotlin-generator/src/test/resources/record-as-default.avsc"
            )

        /** Invalid schemas on purpose */
        val UNPARSEABLE_FILES =
            setOf(
                // references an undefined type, to test kotlin-generator's failure
                "kotlin-generator/src/test/resources/types-across-multiple-files-fail/type-record-without-namespace.avsc"
            )

        val GENERATED_SCHEMAS: List<KSerializer<*>> =
            listOf(
                serializer<Everything>(),
                serializer<Node>(),
                serializer<Tree>(),
                serializer<Shape>(),
                serializer<Suit>(),
                serializer<Wrapper>(),
                serializer<List<Map<String, Everything?>>>(),
                serializer<Map<String, Shape?>>(),
                serializer<String?>(),
                serializer<Int>()
            )

        fun schemaFiles(rootDir: File): List<File> =
            listOf("core/src/jvmTest/resources", "kotlin-generator/src/test/resources")
                .map { rootDir.resolve(it) }
                .flatMap { dir ->
                    dir.walkTopDown().filter { it.isFile && (it.extension == "avsc" || it.extension == "json") }.toList()
                }
                .sorted()

        /**
         * Every parseable schema file, by path relative to [rootDir], parsed by Apache and by avro4k: fresh instances on each call.
         * Files are parsed per directory, sharing the known types, as some of them reference types defined in other files.
         */
        fun parseSchemaFiles(rootDir: File): List<Pair<String, Pair<Schema, AvroSchema>>> =
            schemaFiles(rootDir).groupBy { it.parentFile }.flatMap { (dir, files) -> parseDirectory(dir, files, rootDir) }

        /**
         * Parses each file on its own. The files that reference types defined in other files of the same directory
         * are then parsed with all the directory's files, sharing the known types.
         */
        fun parseDirectory(
            dir: File,
            files: List<File>,
            rootDir: File,
        ): List<Pair<String, Pair<Schema, AvroSchema>>> {
            val results = mutableListOf<Pair<String, Pair<Schema, AvroSchema>>>()
            val needingOtherFiles =
                files.filter { file ->
                    if (file.relativeTo(rootDir).path in UNPARSEABLE_FILES) return@filter false
                    val apacheSchema =
                        try {
                            Schema.Parser().parse(file)
                        } catch (_: AvroRuntimeException) {
                            return@filter true
                        }
                    results += file.relativeTo(rootDir).path to (apacheSchema to AvroSchema.fromJsonString(file.readText()))
                    false
                }
            if (needingOtherFiles.isEmpty()) return results

            val parser = Schema.Parser()
            val knownAvro4kTypes = mutableMapOf<String, AvroSchema>()
            val remaining = files.filter { it.relativeTo(rootDir).path !in UNPARSEABLE_FILES }.toMutableList()
            // retry until no progress, as files may reference types of files parsed later
            while (remaining.isNotEmpty()) {
                val parsed =
                    remaining.filter { file ->
                        val apacheSchema =
                            try {
                                parser.parse(file)
                            } catch (_: AvroRuntimeException) {
                                return@filter false
                            }
                        val avro4kSchema = AvroSchema.fromJsonString(file.readText(), knownAvro4kTypes)
                        if (file in needingOtherFiles) {
                            results += file.relativeTo(rootDir).path to (apacheSchema to avro4kSchema)
                        }
                        true
                    }
                if (parsed.isEmpty()) break
                remaining -= parsed.toSet()
            }
            check(remaining.isEmpty()) { "Unparseable schema files in $dir: ${remaining.map { it.relativeTo(rootDir).path }}" }
            return results
        }

        /** Re-parses the schema from its json, after going through avro4k, to get the coerced defaults as json nodes */
        fun Schema.withNormalizedDefaults(): Schema = Schema.Parser().parse(convertUncached().convertUncached().toString())
    }
}

@Serializable
@SerialName("interop.Node")
private data class Node(
    val value: Int,
    val next: Node? = null,
)

@Serializable
@SerialName("interop.Tree")
private data class Tree(
    val children: List<Tree>,
    val byName: Map<String, Tree>,
)

@Serializable
@SerialName("interop.Suit")
private enum class Suit {
    HEARTS,

    @AvroEnumDefault
    SPADES,
}

@Serializable
@SerialName("interop.Shape")
private sealed interface Shape {
    @Serializable
    @SerialName("interop.Circle")
    data class Circle(val radius: Double) : Shape

    @Serializable
    @SerialName("interop.other.Square")
    data class Square(val side: Double) : Shape

    @Serializable
    @SerialName("interop.Empty")
    data object Empty : Shape
}

@JvmInline
@Serializable
private value class Wrapper(val value: String)

@Serializable
@SerialName("interop.Everything")
@AvroDoc("A record with every kind of schema")
@AvroAlias("interop.OldEverything", "OtherName")
@AvroProp("custom", "value")
@AvroProp("jsonProp", """{"a":[1,2,{"b":null}]}""")
private data class Everything(
    val int: Int,
    val long: Long,
    val float: Float,
    val double: Double,
    val boolean: Boolean,
    val string: String,
    val bytes: ByteArray,
    @AvroFixed(8) val fixed: ByteArray,
    @AvroDecimal(scale = 2, precision = 8) @Contextual val decimal: BigDecimal,
    @Contextual val uuid: UUID,
    @Contextual val date: LocalDate,
    @Contextual val time: LocalTime,
    @Contextual val dateTime: LocalDateTime,
    @Contextual val instant: Instant,
    val nullable: String?,
    @AvroDefault("42") val withDefault: Int,
    @AvroDefault("4.5") val floatWithDefault: Float,
    @AvroDefault("[1, 2]") val listWithDefault: List<Long>,
    @AvroDefault("HEARTS") val enumWithDefault: Suit,
    @AvroDefault("null") val nullableWithDefault: Node?,
    val list: List<Node>,
    val set: Set<Int>,
    val map: Map<String, Node?>,
    val nestedCollections: Map<String, List<Map<String, Int?>>>,
    val suit: Suit,
    val shape: Shape,
    val nullableShape: Shape?,
    val tree: Tree,
    @AvroAlias("oldName", "otherOldName") @AvroDoc("a field doc") @AvroProp("fieldProp", "1") val aliased: String,
    val wrapper: Wrapper,
    @AvroStringable val stringable: Int,
)

/** The uncached conversions, which compare the converted schemas rather than return the cached, paired, instances. */
internal fun Schema.convertUncached(): AvroSchema = apacheToAvro4kUncached(this)

internal fun AvroSchema.convertUncached(): Schema = avro4kToApacheUncached(this)