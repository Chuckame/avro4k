import com.github.avrokotlin.benchmark.internal.SimpleDatasClass as KotlinSimpleDatasClass
import com.github.avrokotlin.benchmark.internal.StatsEntry as KotlinStatsEntry
import com.github.avrokotlin.benchmark.internal.Stranger as KotlinStranger

/**
 * Converts avro4k's models into the generated `SpecificRecord` classes, once, in `@Setup`.
 *
 * There is no hand-written Apache model here, unlike `internal/apache`: the classes in this package
 * are generated by `:benchmark:generateSpecificRecords` from the `.avsc` files under
 * `src/main/avro`, which are themselves `Avro.schema<T>()` verbatim. So the field set, the field
 * order and every type in it are avro4k's by construction, and the equivalence gate re-proves that
 * on every trial by comparing each generated `SCHEMA$` against `Avro.schema<T>()`.
 *
 * Four of avro4k's types land differently in a generated class, and none of them is a choice this
 * file made - they are what Avro's `SpecificCompiler` emits for that schema:
 *
 * | avro4k | schema | generated |
 * |---|---|---|
 * | `ByteArray` | `bytes` | `java.nio.ByteBuffer` |
 * | `Char?` | `["null", int(logicalType char)]` | `Integer` - `char` is avro4k's own logical type, unknown to Avro |
 * | `BigDecimal?` (`@AvroStringable`) | `["null", string]` | `String` |
 * | `Partner?` | `["null", BadPartner, GoodPartner, Stranger]` | `Object` - the compiler's shape for a multi-branch union |
 *
 * The `BigDecimal` one is the only one with a measurable consequence, and it is disclosed rather
 * than hidden: the specific model stores the already-stringified balance, so its `write` does not
 * re-`toString()` a `BigDecimal` per record the way avro4k's does. One field out of twenty in
 * `complex`; `simple` and `lists` have no such field. See docs/plans/notes/a7.md.
 */
internal fun KotlinClients.toSpecific(): Clients = Clients(clients.map { it.toSpecific() })

private fun KotlinClient.toSpecific(): Client = Client(
    id,
    index,
    isActive,
    balance?.toString(),
    picture?.let { ByteBuffer.wrap(it) },
    age,
    eyeColor?.toSpecific(),
    name,
    gender?.code,
    company,
    emails.asList(),
    phones.asList(),
    address,
    about,
    registered,
    latitude,
    longitude,
    tags,
    partner?.toSpecific(),
    // A `LinkedHashMap` copy, not the map itself: the generated setter stores whatever it is given,
    // and Avro's encoder writes entries in iteration order, so the order has to be avro4k's for the
    // gate's byte comparison to mean anything. avro4k's own map already is a `LinkedHashMap`; the
    // copy makes that explicit rather than incidental.
    LinkedHashMap(map),
)

private fun KotlinEyeColor.toSpecific(): EyeColor = when (this) {
    KotlinEyeColor.BROWN -> EyeColor.BROWN
    KotlinEyeColor.BLUE -> EyeColor.BLUE
    KotlinEyeColor.GREEN -> EyeColor.GREEN
}

private fun KotlinPartner.toSpecific(): Any = when (this) {
    is KotlinGoodPartner -> GoodPartner(id, name, since)
    is KotlinBadPartner -> BadPartner(id, name, since)
    KotlinStranger.KNOWN_STRANGER -> Stranger.KNOWN_STRANGER
    KotlinStranger.UNKNOWN_STRANGER -> Stranger.UNKNOWN_STRANGER
}

internal fun KotlinSimpleDatasClass.toSpecific(): SimpleDatasClass =
    SimpleDatasClass(data.map { it.toSpecific() })

private fun KotlinSimpleDataClass.toSpecific(): SimpleDataClass = SimpleDataClass(
    bool,
    // `Byte`/`Short` have no Avro type; avro4k writes them as `int`, so the generated class has an
    // `int` field. Widening here is the same widening avro4k's encoder does.
    byte.toInt(),
    short.toInt(),
    int,
    long,
    float,
    double,
    string,
    ByteBuffer.wrap(bytes),
)

internal fun KotlinListWrapperDatasClass.toSpecific(): ListWrapperDatasClass =
    ListWrapperDatasClass(data.map { it.toSpecific() })

private fun KotlinListWrapperDataClass.toSpecific(): ListWrapperDataClass =
    ListWrapperDataClass(index, entries.map { it.toSpecific() })

private fun KotlinStatsEntry.toSpecific(): StatsEntry = StatsEntry(elementId, values)
