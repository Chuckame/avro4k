/**
 * M3-10: the common Parsing Canonical Form and CRC-64-AVRO fingerprint are byte-identical to Apache's
 * `SchemaNormalization` (the tie-breaker wherever it and the spec text could disagree), for every schema of the
 * `jvmTest` resource corpus, for schemas generated by avro4k, and for hand-written corner cases. Each Apache schema is
 * converted to the model with apache-interop's `toAvro4k()` (M3-01's rule: schema-typed calls go through the bridge).
 */
internal class SchemaFingerprintDifferentialTest : StringSpec({
    val resources: List<Pair<String, Schema>> by lazy {
        val dir = File(SchemaFingerprintDifferentialTest::class.java.getResource("/basic.json")!!.toURI()).parentFile
        dir.listFiles { f -> f.name.endsWith(".json") }!!.sortedBy { it.name }.map { it.name to Schema.Parser().parse(it) }
    }
    val generated: List<Pair<String, Schema>> by lazy {
        GENERATED.map { serializer -> "generated ${serializer.descriptor.serialName}" to Avro.apacheSchema(serializer) }
    }
    val handWritten: List<Pair<String, Schema>> by lazy {
        HAND_WRITTEN.mapIndexed { i, json -> "hand-written #$i" to Schema.Parser().parse(json) }
    }

    fun assertSameAsApache(
        name: String,
        apache: Schema,
        model: AvroSchema,
    ) {
        withClue("$name: $apache") {
            model.toParsingCanonicalForm() shouldBe SchemaNormalization.toParsingForm(apache)
            model.parsingFingerprint64() shouldBe SchemaNormalization.parsingFingerprint64(apache)
            model.parsingFingerprintCrc64AvroBytes().toList() shouldBe SchemaNormalization.parsingFingerprint("CRC-64-AVRO", apache).toList()
        }
    }

    "every resource schema parses: all 52 are compared, none is excluded" {
        resources.size shouldBe 52
    }

    "the resource schemas have Apache's canonical form and fingerprint" {
        resources.forEach { (name, schema) -> assertSameAsApache(name, schema, schema.toAvro4k()) }
    }

    "the schemas generated by avro4k have Apache's canonical form and fingerprint" {
        generated.forEach { (name, schema) -> assertSameAsApache(name, schema, schema.toAvro4k()) }
    }

    "the hand-written corner cases have Apache's canonical form and fingerprint" {
        handWritten.forEach { (name, schema) -> assertSameAsApache(name, schema, schema.toAvro4k()) }
    }

    "every sub-schema of the corpus, taken alone, has Apache's canonical form and fingerprint" {
        // a named type deep in a schema is written in full when it is the root, as a name when seen before
        var compared = 0
        var named = 0
        (resources + generated + handWritten).forEach { (name, schema) ->
            val model = schema.toAvro4k()
            walk(schema, model, java.util.IdentityHashMap()) { apache, sub ->
                assertSameAsApache("$name / ${apache.fullName}", apache, sub)
                compared++
                if (sub is AvroSchema.NamedSchema) named++
            }
        }
        compared shouldBeGreaterThan 450
        named shouldBeGreaterThan 100
    }

    "multi-byte UTF-8 names are hashed as UTF-8" {
        val apache =
            Schema.Parser(NameValidator.NO_VALIDATION).parse(
                """{"type":"record","name":"Café","namespace":"ns.été","fields":[{"name":"日本","type":"int"},{"name":"emoji😀","type":{"type":"enum","name":"Ω","symbols":["ä","β"]}}]}"""
            )
        assertSameAsApache("utf-8", apache, apache.toAvro4k())
    }

    "two distinct but equal instances of a named type: the second is written as its name, like Apache" {
        val inner = { RecordSchema(Name("Inner", "ns"), listOf(RecordSchema.Field("x", IntSchema()))) }
        val model =
            RecordSchema(
                Name("Outer", "ns"),
                listOf(RecordSchema.Field("a", inner()), RecordSchema.Field("b", inner()), RecordSchema.Field("c", UnionSchema(inner(), StringSchema())))
            )
        assertSameAsApache("distinct instances", model.toApacheSchema(), model)
        model.toParsingCanonicalForm() shouldBe
            """{"name":"ns.Outer","type":"record","fields":[{"name":"a","type":{"name":"ns.Inner","type":"record","fields":[{"name":"x","type":"int"}]}},{"name":"b","type":"ns.Inner"},{"name":"c","type":["ns.Inner","string"]}]}"""
    }

    "a recursive model built with a LockableList has Apache's canonical form and fingerprint" {
        val fields = LockableList<RecordSchema.Field>()
        val node = RecordSchema(Name("Node", "rec"), fields, doc = "a node", props = mapOf("p" to JsonPrimitive(1)))
        fields += RecordSchema.Field("value", StringSchema(mapOf("logicalType" to JsonPrimitive("uuid"))))
        fields += RecordSchema.Field("next", UnionSchema(AvroSchema.NullSchema(), node), defaultValue = kotlinx.serialization.json.JsonNull)
        fields += RecordSchema.Field("children", AvroSchema.ArraySchema(node))
        fields.lock()
        assertSameAsApache("recursive model", node.toApacheSchema(), node)
    }

    "CRC-64-AVRO over bytes and strings matches Apache's fingerprint64, unpaired surrogates included" {
        val random = Random(42)
        repeat(2_000) {
            val bytes = random.nextBytes(random.nextInt(0, 64))
            crc64Avro(bytes) shouldBe SchemaNormalization.fingerprint64(bytes)
            bytes.let { crc64Avro(it).toLittleEndianBytes().toList() shouldBe SchemaNormalization.fingerprint("CRC-64-AVRO", it).toList() }

            // chars drawn from every UTF-16 range: ASCII, 2-byte, 3-byte, surrogates (paired or not)
            val text =
                buildString {
                    repeat(random.nextInt(0, 32)) {
                        when (random.nextInt(5)) {
                            0 -> append(random.nextInt(0, 0x80).toChar())
                            1 -> append(random.nextInt(0x80, 0x800).toChar())
                            2 -> append(random.nextInt(0x800, 0xd800).toChar())
                            3 -> append(random.nextInt(0xd800, 0xe000).toChar())
                            else -> append(Character.toChars(random.nextInt(0x10000, 0x110000)))
                        }
                    }
                }
            withClue(text.map { it.code.toString(16) }) {
                crc64Avro(text) shouldBe SchemaNormalization.fingerprint64(text.toByteArray(Charsets.UTF_8))
            }
        }
    }
})

/** Walks both trees in parallel, visiting each named type once (a recursive schema would loop otherwise). */
private fun walk(
    apache: Schema,
    model: AvroSchema,
    seen: java.util.IdentityHashMap<Schema, Unit>,
    visit: (Schema, AvroSchema) -> Unit,
) {
    if (seen.put(apache, Unit) != null) return
    visit(apache, model)
    when (apache.type) {
        Schema.Type.RECORD -> apache.fields.forEachIndexed { i, f -> walk(f.schema(), (model as RecordSchema).fields[i].schema, seen, visit) }
        Schema.Type.UNION -> apache.types.forEachIndexed { i, t -> walk(t, (model as UnionSchema).types[i], seen, visit) }
        Schema.Type.ARRAY -> walk(apache.elementType, (model as AvroSchema.ArraySchema).elementSchema, seen, visit)
        Schema.Type.MAP -> walk(apache.valueType, (model as AvroSchema.MapSchema).valueSchema, seen, visit)
        else -> Unit
    }
}

