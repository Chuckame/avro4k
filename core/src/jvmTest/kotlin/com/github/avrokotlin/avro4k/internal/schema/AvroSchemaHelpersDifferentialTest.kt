// core/src/jvmMain/.../internal/helpers.kt
private fun Schema.asSchemaListRef(): List<Schema> {
    if (!isUnion) return listOf(this)
    return types
}

private fun Schema.isNamedSchemaRef(): Boolean {
    return when (this.type) {
        Schema.Type.RECORD, Schema.Type.ENUM, Schema.Type.FIXED -> true
        else -> false
    }
}

private fun Schema.nonFailingAliasesRef(): Set<String> {
    return if (isNamedSchemaRef()) {
        aliases
    } else {
        emptySet()
    }
}

private fun Schema.isFullNameOrAliasMatchRef(
    fullName: String,
    aliases: () -> Set<String>,
): Boolean {
    return isFullNameMatchRef(fullName) || aliases().any { isFullNameMatchRef(it) }
}

private fun Schema.isFullNameMatchRef(fullNameToMatch: String): Boolean {
    return fullName == fullNameToMatch || (isNamedSchemaRef() && aliases.any { it == fullNameToMatch })
}

// core/src/jvmMain/.../AvroEncoder.kt
private fun Schema.getIndexLogicallyTypedRef(
    logicalTypeName: String,
    vararg oneOf: Schema.Type,
): Int? {
    return oneOf.firstNotNullOfOrNull { expectedType ->
        when (expectedType) {
            Schema.Type.FIXED, Schema.Type.RECORD, Schema.Type.ENUM -> types.indexOfFirst { it.type == expectedType && it.logicalType?.name == logicalTypeName }.takeIf { it >= 0 }
            else -> getIndexNamed(expectedType.getName())?.takeIf { types[it].logicalType?.name == logicalTypeName }
        }
    }
}

private fun Schema.getIndexNamedOrAliasedRef(expectedName: String): Int? {
    return getIndexNamed(expectedName)
        ?: types.indexOfFirst { it.isNamedSchemaRef() && it.aliases.contains(expectedName) }.takeIf { it >= 0 }
}

private fun Schema.getIndexTypedRef(expectedType: Schema.Type): Int? {
    @Suppress("UsePropertyAccessSyntax")
    return getIndexNamed(expectedType.getName())
}

// core/src/jvmMain/.../internal/schema/ClassVisitor.kt
private fun Schema.moveToHeadOfUnionRef(predicate: (Schema) -> Boolean): Schema {
    if (!isUnion) {
        return this
    }
    types.indexOfFirst(predicate).let { index ->
        if (index == -1) {
            return this
        }
        return moveToHeadOfUnionRef(index)
    }
}

private fun Schema.moveToHeadOfUnionRef(typeIndex: Int): Schema {
    if (!isUnion || typeIndex >= types.size) {
        return this
    }
    return Schema.createUnion(types.toMutableList().apply { add(0, removeAt(typeIndex)) })
}

private fun Schema.moveToTailOfUnionRef(predicate: (Schema) -> Boolean): Schema {
    if (!isUnion) {
        return this
    }
    types.indexOfFirst(predicate).let { index ->
        if (index == -1) {
            return this
        }
        return moveToTailOfUnionRef(index)
    }
}

private fun Schema.moveToTailOfUnionRef(typeIndex: Int): Schema {
    if (!isUnion || typeIndex >= types.size) {
        return this
    }
    return Schema.createUnion(types.toMutableList().apply { add(removeAt(typeIndex)) })
}

// core/src/jvmMain/.../internal/schema/MapVisitor.kt
private fun Schema.isNonNullScalarTypeRef(): Boolean =
    when (type) {
        Schema.Type.BOOLEAN,
        Schema.Type.INT,
        Schema.Type.LONG,
        Schema.Type.FLOAT,
        Schema.Type.DOUBLE,
        Schema.Type.STRING,
        Schema.Type.ENUM,
        Schema.Type.BYTES,
        Schema.Type.FIXED,
        -> true

        Schema.Type.NULL,
        Schema.Type.ARRAY,
        Schema.Type.MAP,
        Schema.Type.RECORD,
        null,
        -> false

        Schema.Type.UNION -> types.all { it.isNonNullScalarTypeRef() }
    }

