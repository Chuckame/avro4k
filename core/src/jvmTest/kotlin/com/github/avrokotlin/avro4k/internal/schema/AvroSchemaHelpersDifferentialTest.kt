private fun bigRecord(schema: Schema): GenericData.Record {
    val itemSchema = schema.getField("arr").schema().elementType

    fun item(x: Int, next: GenericData.Record?) =
        GenericData.Record(itemSchema).apply {
            put("x", x)
            put("tags", List(x % 4) { "tag-$x-$it" })
            put("next", next)
        }
    return GenericData.Record(schema).apply {
        put("i", 42)
        put("s", "hello")
        put("u", "a string branch")
        put("e", GenericData.EnumSymbol(schema.getField("e").schema(), "B"))
        put("f", GenericData.Fixed(schema.getField("f").schema(), byteArrayOf(1, 2, 3)))
        put("b", ByteBuffer.wrap(ByteArray(100) { it.toByte() }))
        put("arr", List(60) { item(it, if (it % 3 == 0) item(it + 1000, null) else null) })
        put("m", (0 until 25).associate { "key-$it" to List(it % 7) { n -> n * 1_000_000_007L } })
        put("d", 1.5)
        put("fl", 2.5f)
        put("bo", true)
        put("n", null)
    }
