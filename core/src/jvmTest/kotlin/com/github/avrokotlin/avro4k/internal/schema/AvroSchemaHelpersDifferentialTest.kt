// ---- the walk ----

private fun walk(
    apache: Schema,
    model: AvroSchema,
    seen: MutableSet<Schema> = Collections.newSetFromMap(IdentityHashMap()),
    visit: (Schema, AvroSchema) -> Unit,
) {
    visit(apache, model)
    when (apache.type!!) {
        Schema.Type.UNION -> apache.types.forEachIndexed { i, branch -> walk(branch, model.types[i], seen, visit) }

        Schema.Type.ARRAY -> walk(apache.elementType, model.elementType, seen, visit)

        Schema.Type.MAP -> walk(apache.valueType, model.valueType, seen, visit)

        Schema.Type.RECORD -> {
            if (!seen.add(apache)) return
            apache.fields.forEachIndexed { i, field -> walk(field.schema(), (model as RecordSchema).fields[i].schema, seen, visit) }
        }

        else -> {}
    }
}

private fun Schema.Type.toModel(): Type = Type.valueOf(name)

private fun Schema.containsNamedSchema(): Boolean =
    when (type!!) {
        Schema.Type.UNION -> types.any { it.isNamedSchemaRef() || it.containsNamedSchema() }
        Schema.Type.ARRAY -> elementType.let { it.isNamedSchemaRef() || it.containsNamedSchema() }
        Schema.Type.MAP -> valueType.let { it.isNamedSchemaRef() || it.containsNamedSchema() }
        else -> false
    }

private fun AvroSchema.branchNames(): Any = if (isUnion) types.map { it.fullName } else fullName

private fun Schema.branchNames(): Any = if (isUnion) types.map { it.fullName } else fullName

